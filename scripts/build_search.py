#!/usr/bin/env python3
"""
Build assets/js/search-index.js for the site search.

Standard library only. Run after adding or editing pages:

    python3 scripts/build_search.py

Every public .html page becomes one search entry (title, description,
headings and a trimmed body). Floor plans are not listed here: search.js
reads them from plans.js at runtime, so prices and sizes stay in one place.
"""

from __future__ import annotations

import json
import re
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP = {"404.html", "thank-you.html", "plan.html", "search.html"}
SUFFIX = " | Stoneward Construction"
BODY_LIMIT = 1400


class Page(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.title = ""
        self.desc = ""
        self.heads: list[str] = []
        self.body: list[str] = []
        self._stack: list[str] = []
        self._in_main = False
        self._buf = ""

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "meta" and a.get("name") == "description":
            self.desc = (a.get("content") or "").strip()
        if tag == "main":
            self._in_main = True
        if tag in {"title", "h1", "h2", "h3", "script", "style"}:
            self._stack.append(tag)
            self._buf = ""

    def handle_endtag(self, tag):
        if self._stack and self._stack[-1] == tag:
            self._stack.pop()
            text = re.sub(r"\s+", " ", self._buf).strip()
            if tag == "title":
                self.title = text
            elif tag in {"h1", "h2", "h3"} and text:
                self.heads.append(text)
        if tag == "main":
            self._in_main = False

    def handle_data(self, data):
        if self._stack:
            if self._stack[-1] in {"script", "style"}:
                return
            self._buf += data
        if self._in_main and not (self._stack and self._stack[-1] in {"script", "style"}):
            self.body.append(data)


def kind(name: str) -> str:
    if name.endswith("-adu.html"):
        return "City"
    if name in {"utah-adu-cities.html"}:
        return "Cities"
    if name == "utah-adu-law-sb284.html":
        return "Utah law"
    if name in {"adu-guides.html", "faq.html", "how-it-works.html"}:
        return "Guide"
    return "Page"


def main() -> None:
    entries = []
    for path in sorted(ROOT.glob("*.html")):
        if path.name in SKIP:
            continue
        parser = Page()
        parser.feed(path.read_text(encoding="utf-8"))
        title = parser.title.removesuffix(SUFFIX).strip()
        body = re.sub(r"\s+", " ", " ".join(parser.body)).strip()[:BODY_LIMIT]
        url = "" if path.name == "index.html" else path.stem
        entries.append(
            {
                "t": title,
                "u": url,
                "k": kind(path.name),
                "d": parser.desc,
                "h": " | ".join(parser.heads[:14]),
                "b": body,
            }
        )
    out = ROOT / "assets" / "js" / "search-index.js"
    out.write_text(
        "/* Generated by scripts/build_search.py. Do not edit by hand. */\n"
        "window.SEARCH_INDEX = " + json.dumps(entries, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"search index: {len(entries)} pages, {out.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
